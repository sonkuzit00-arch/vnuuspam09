// Справочники сервиса. Хранятся как обычные строки (SQLite не поддерживает
// Prisma enum), валидируются на уровне форм и API через zod.

// Каналы поступления обращений — ровно по актуальному списку. Каналы,
// начинающиеся на «ГД;», для количественно-качественного анализа в общем
// своде объединяются в одну группу «ГД» независимо от конкретного подканала
// (см. getChannelGroup ниже) — так его требуют вести для отчёта в ЦУР и т.п.,
// но в аналитике это один хэштег.
export const SOURCE_CHANNEL_GROUPS: Record<string, readonly string[]> = {
  "ГД": [
    "ГД; САДД / «Дело»",
    "ГД; почта",
    "ГД; электронная почта",
    "ГД; соцсети - комментарии",
    "ГД; соцсети ДГД, личные сообщения",
  ],
  "Приём и поездки": ["приём и рабочие поездки", "личные сообщения ДГД"],
  "ОП": ["общественные приёмные (ОП)", "сайт ОП (электронная форма)"],
  "КАУ / КЦ": ["КАУ", "колл-центр"],
} as const;

export const SOURCE_CHANNELS = Object.values(SOURCE_CHANNEL_GROUPS).flat() as [string, ...string[]];

/** Группа канала для аналитики — все «ГД; …» подканалы объединяются в «ГД». */
export function getChannelGroup(channel: string): string {
  for (const [group, channels] of Object.entries(SOURCE_CHANNEL_GROUPS)) {
    if ((channels as readonly string[]).includes(channel)) return group;
  }
  return "Прочее";
}

